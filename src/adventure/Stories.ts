/** La abuela le recuerda a Juan su propósito, según cómo va la ronda. */
export function abuelaNudge(calmed: number, total = MYTH_IDS.length): string {
  const left = total - calmed;
  if (calmed === 0) return `SU ABUELO DECÍA: "AL ESPANTO NO SE LE GANA CON RABIA, SE LE GANA CON RESPETO". LOS ${left} ANDAN SUELTOS, MIJO: SIGA LAS SEÑALES Y PARE LA OREJA.`;
  if (calmed <= 3) return `¿YA LE HABLARON DE JOAQUÍN? ESOS ESPANTOS LO CONOCÍAN MÁS QUE YO, JA. QUEDAN ${left}: SIGA LAS SEÑALES Y PARE LA OREJA.`;
  if (calmed <= 6) return `ME CONTARON QUE LO VIERON PELEANDO CON EL MACHETE DEL ABUELO... ME PARECIÓ VERLO A ÉL DE MUCHACHO. QUEDAN ${left}, MIJO. ¡NO SE ME DUERMA!`;
  return `YA CASI, MIJO. ${left === 1 ? 'UNO SOLO' : `${left} NO MÁS`} Y ESTA NOCHE TAN LARGA POR FIN SE ACABA. ¡ANDE, QUE LAS DOCE NO ESPERAN!`;
}
