export const MYTH_IDS = Object.keys(MYTH_ARC) as MythId[];

const pick = <T>(list: T[], roll: number): T => list[Math.min(list.length - 1, Math.max(0, Math.floor(roll * list.length)))];

/** Reto del mito antes de pelear, al azar entre sus variantes. */
export function mythTaunt(id: FighterId, roll: number): string {
  const arc = MYTH_ARC[id as MythId] as MythArc | undefined;
  return arc ? pick(arc.taunts, roll) : '¡EN GUARDIA!';
}

/** Lo que dice el mito ya calmado; si fue el último de la ronda, cierra con el aviso de volver donde la abuela. */
export function calmedWords(id: FighterId, last: boolean): string[] {
  const arc = MYTH_ARC[id as MythId] as MythArc | undefined;
  const words = arc ? [...arc.calmed] : [];
  if (last) words.push('YA NO QUEDA NINGUNO SUELTO. LA RONDA ESTÁ COMPLETA, NIETO DE JOAQUÍN. VE DONDE ROSA: ELLA SABE LO QUE SIGUE.');
  return words;
}

/** Cuenta de la ronda después de calmar a un mito. */
export function roundTally(calmed: number, total = MYTH_IDS.length): string {
  const left = total - calmed;
  if (left <= 0) return `MITOS CALMADOS: ${calmed} DE ${total}. ¡LA RONDA ESTÁ COMPLETA! VUELVA CON LA ABUELA ROSA.`;
  return `MITOS CALMADOS: ${calmed} DE ${total}. ${left === 1 ? 'FALTA UNO' : `FALTAN ${left}`} PA' CERRAR LA RONDA DEL ABUELO.`;
}

